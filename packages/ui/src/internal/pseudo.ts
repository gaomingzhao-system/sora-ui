/**
 * Turn a message into bracketed, accented, lengthened text while leaving
 * `{placeholders}` untouched. Works for any flat message dictionary.
 */
export function pseudoLocalize(message: string): string {
  const body = message
    .split(/(\{\w+\})/)
    .map((part) =>
      part.startsWith('{') ? part : [...part].map((character) => ACCENTS[character] ?? character).join(''),
    )
    .join('')
  const padding = ' ~'.repeat(Math.max(1, Math.ceil([...message].length * 0.2)))
  return `[${body}${padding}]`
}

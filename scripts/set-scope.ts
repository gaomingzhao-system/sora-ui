/**
 * Renames the placeholder npm scope.
 *
 * The packages are developed as `@your-scope/ui` and `@your-scope/theme`.
 * Before publishing, run this once with the real scope:
 *
 *   node scripts/set-scope.ts @acme            rewrite every tracked file
 *   node scripts/set-scope.ts @acme --dry-run  only report what would change
 *
 * Every tracked text file is rewritten (package names, imports, aliases,
 * documentation). The lockfile is left alone: run `pnpm install` afterwards
 * to regenerate it, then `pnpm build && pnpm check:package`.
 */
import { execFileSync } from 'node:child_process'
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const PLACEHOLDER = '@your-scope'

const scope = process.argv.slice(2).find((argument) => !argument.startsWith('--'))
const dryRun = process.argv.includes('--dry-run')

// npm scope: lowercase, URL-safe, no leading dot or underscore.
if (!scope || !/^@[a-z0-9][a-z0-9._-]*$/.test(scope)) {
  console.error('usage: node scripts/set-scope.ts @your-real-scope [--dry-run]')
  process.exit(2)
}
if (scope === PLACEHOLDER) {
  console.error(`${PLACEHOLDER} is the placeholder; pass the scope you publish under.`)
  process.exit(2)
}

const tracked = execFileSync('git', ['ls-files', '-z'], { cwd: root, encoding: 'utf8' })
  .split('\0')
  .filter(Boolean)
  // The lockfile is regenerated by `pnpm install`; this script must keep describing the placeholder.
  .filter((file) => file !== 'pnpm-lock.yaml' && file !== 'scripts/set-scope.ts')

let files = 0
let occurrences = 0
for (const file of tracked) {
  const buffer = await readFile(`${root}${file}`)
  if (buffer.includes(0)) continue // binary
  const text = buffer.toString('utf8')
  const count = text.split(PLACEHOLDER).length - 1
  if (count === 0) continue
  files++
  occurrences += count
  if (!dryRun) await writeFile(`${root}${file}`, text.replaceAll(PLACEHOLDER, scope))
}

console.log(
  `${dryRun ? 'would replace' : 'replaced'} ${occurrences} occurrences of ${PLACEHOLDER} with ${scope} in ${files} files`,
)
if (!dryRun) console.log('Next: pnpm install && pnpm build && pnpm check:package')

/**
 * Installs the *packed* library in applications that live outside the
 * workspace and proves it works there.
 *
 *   1. pack @your-scope/theme and @your-scope/ui (the published artifacts)
 *   2. copy each consumer to .artifacts/consumers/<name> (its own pnpm root:
 *      no workspace link and no source alias can leak in)
 *   3. `pnpm install` the tarballs, type-check with vue-tsc, build with Vite
 *   4. assert what the installed package graph and the bundle contain
 *   5. run the Playwright `consumer` project against the built applications
 *
 *   node scripts/verify-consumer.ts            build packages, then verify
 *   node scripts/verify-consumer.ts --no-build reuse the existing dist folders
 *   node scripts/verify-consumer.ts --no-e2e   skip step 5 (no browser needed)
 *
 * The built consumers stay in .artifacts/consumers, where `pnpm test:e2e`
 * picks them up as well.
 */
import { existsSync } from 'node:fs'
import { cp, mkdir, readFile, readdir, realpath, rm, writeFile } from 'node:fs/promises'
import { consumerDir, gzipSizeOfFiles, kib, packPackages, root, run } from './shared.ts'
import type { PackedPackage } from './shared.ts'

interface Consumer {
  name: string
  source: string
  /** Packages that must NOT be installed (optional peers the app does not use). */
  absent: readonly string[]
  /** Strings that must not appear in the built JavaScript. */
  forbidden: readonly RegExp[]
  /** Strings that must appear in the built JavaScript or CSS. */
  required: readonly RegExp[]
}

const CONSUMERS: readonly Consumer[] = [
  {
    name: 'basic',
    source: 'tests/fixtures/consumer-basic',
    absent: ['@formisch/vue', 'valibot', 'petite-vue-i18n'],
    forbidden: [
      /Next page/, // the English message dictionary (Button and Card need no text)
      /次のページ|الصفحة التالية/, // any other locale
      /sora-dialog|sora-combobox|sora-toast/, // unrelated components' markup
    ],
    required: [/sora-button/, /sora-card/],
  },
  {
    name: 'full',
    source: 'apps/consumer',
    absent: [],
    forbidden: [],
    required: [/sora-button/, /sora-dialog/, /sora-pagination/],
  },
]

const started = performance.now()
if (!process.argv.includes('--no-build')) {
  run('pnpm', ['--filter', '@your-scope/theme', 'build'])
  run('pnpm', ['--filter', '@your-scope/ui', 'build'])
}
const packed = await packPackages()
const tarballOf = (name: string): PackedPackage => {
  const found = packed.find((entry) => entry.name === name)
  if (!found) throw new Error(`no tarball for ${name}`)
  return found
}

await rm(consumerDir, { recursive: true, force: true })
await mkdir(consumerDir, { recursive: true })

const report: Record<string, unknown> = {}

for (const consumer of CONSUMERS) {
  const dir = `${consumerDir}/${consumer.name}`
  await cp(`${root}${consumer.source}`, dir, {
    recursive: true,
    filter: (source) => !/\/(node_modules|dist)(\/|$)/.test(source),
  })

  // Point the library at the tarball. Everything else stays exactly as committed.
  const manifestPath = `${dir}/package.json`
  const manifest = JSON.parse(await readFile(manifestPath, 'utf8')) as {
    dependencies: Record<string, string>
  }
  manifest.dependencies['@your-scope/ui'] = `file:${tarballOf('@your-scope/ui').tarball}`
  await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`)

  // Its own pnpm root. @your-scope/theme is a real dependency of the ui
  // tarball; until both are on a registry it is taken from its tarball too.
  await writeFile(
    `${dir}/pnpm-workspace.yaml`,
    [
      '# Generated by scripts/verify-consumer.ts',
      'overrides:',
      `  '@your-scope/theme': file:${tarballOf('@your-scope/theme').tarball}`,
      '',
    ].join('\n'),
  )

  run('pnpm', ['install', '--no-frozen-lockfile'], { cwd: dir })

  // The library must come from the tarball, never from the workspace sources.
  const installed = await realpath(`${dir}/node_modules/@your-scope/ui`)
  if (installed.startsWith(`${root}packages/`)) {
    throw new Error(`${consumer.name}: @your-scope/ui resolved to workspace sources (${installed})`)
  }
  if (existsSync(`${installed}/src`)) throw new Error(`${consumer.name}: the installed package contains src/`)
  for (const name of consumer.absent) {
    if (existsSync(`${dir}/node_modules/${name}`)) {
      throw new Error(`${consumer.name}: optional peer ${name} was installed, but this app does not use it`)
    }
  }

  run('pnpm', ['exec', 'vue-tsc', '--noEmit'], { cwd: dir })
  run('pnpm', ['exec', 'vite', 'build', '--logLevel', 'error'], { cwd: dir })

  let js = ''
  let css = ''
  for (const file of await readdir(`${dir}/dist/assets`)) {
    const content = await readFile(`${dir}/dist/assets/${file}`, 'utf8')
    if (file.endsWith('.js')) js += content
    else if (file.endsWith('.css')) css += content
  }
  for (const pattern of consumer.forbidden) {
    if (pattern.test(js)) throw new Error(`${consumer.name}: built JavaScript contains ${pattern.source}`)
  }
  for (const pattern of consumer.required) {
    if (!pattern.test(js) && !pattern.test(css))
      throw new Error(`${consumer.name}: build is missing ${pattern.source}`)
  }
  if (!css.includes('--sora-canvas'))
    throw new Error(`${consumer.name}: the documented CSS import produced no tokens`)

  const sizes = {
    js: await gzipSizeOfFiles(`${dir}/dist/assets`, '.js'),
    css: await gzipSizeOfFiles(`${dir}/dist/assets`, '.css'),
  }
  report[consumer.name] = { dir, dist: `${dir}/dist`, installed, sizes }
  console.log(
    `ok  ${consumer.name.padEnd(6)} installed from tarball, type-checked, built: ` +
      `js ${kib(sizes.js.gzip)} gzip (${sizes.js.files} files), css ${kib(sizes.css.gzip)} gzip`,
  )
}

await writeFile(`${consumerDir}/report.json`, `${JSON.stringify({ packed, consumers: report }, null, 2)}\n`)

if (process.argv.includes('--no-e2e')) {
  console.log('--  e2e    skipped (--no-e2e)')
} else {
  // The applications run in a real browser: rendering, styles, locales, forms, dialog, axe.
  const output = run(
    'pnpm',
    ['exec', 'playwright', 'test', '--project=consumer', '--reporter=line', '--trace', 'off'],
    {
      env: { SORA_E2E_QUIET: '1' },
    },
  )
  const summary = /(\d+) passed[^\n]*/.exec(output)?.[0] ?? 'passed'
  console.log(`ok  e2e    consumer project: ${summary}`)
}

console.log(`verify:consumer passed in ${((performance.now() - started) / 1000).toFixed(1)}s`)

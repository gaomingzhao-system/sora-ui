/**
 * Generates the component reference in docs/components.
 *
 * Nothing in those files is written by hand, so they cannot drift:
 *   - props, models, events, slots and exposed members are read from each
 *     SFC with the TypeScript parser (types, defaults and doc comments),
 *   - purpose, attribute routing, keyboard, accessibility and styling notes
 *     come from the component manifest,
 *   - the example is the component's section of the gallery, which is
 *     type-checked and exercised by the end-to-end tests.
 *
 *   node scripts/generate-docs.ts          write docs/components
 *   node scripts/generate-docs.ts --check  fail when the files are out of date
 */
import { existsSync } from 'node:fs'
import { glob, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { parse } from '@vue/compiler-sfc'
import ts from 'typescript'
import { componentCategories, componentManifest } from '../packages/ui/src/components.manifest.ts'
import type { SoraComponentManifestEntry } from '../packages/ui/src/components.manifest.ts'

const root = fileURLToPath(new URL('..', import.meta.url))
const outDir = `${root}docs/components`
const check = process.argv.includes('--check')
const BANNER =
  '<!-- Generated by scripts/generate-docs.ts from the component source and the manifest. Do not edit. -->'

interface Member {
  name: string
  type: string
  optional: boolean
  doc: string
}
interface Prop extends Member {
  default: string
}
interface Model {
  name: string
  type: string
  detail: string
  doc: string
}
interface Api {
  generic: string
  props: Prop[]
  models: Model[]
  events: Member[]
  slots: Member[]
  exposed: Member[]
}

const oneLine = (text: string): string => text.replace(/\s+/g, ' ').trim()

/**
 * The shared prop vocabulary. Many components take these props with exactly
 * the same meaning, so the sources document them once (SoraField, SoraButton);
 * the reference repeats that meaning wherever a prop has no comment of its own.
 */
const SHARED_PROPS: Readonly<Record<string, string>> = {
  label: 'Label text. It is the accessible name of the control.',
  hint: 'Helper text below the control, announced as its description.',
  error: 'Error message(s). A non-empty value also marks the control invalid and is announced with it.',
  required:
    'Marks the field as required: the native `required` attribute plus a decorative marker on the label.',
  disabled: 'Disables the control, with the native `disabled` attribute where the element has one.',
  invalid: 'Marks the control invalid (`aria-invalid`) without showing a message.',
  id: 'Id of the native control. Generated (and stable) when omitted.',
  hideLabel: 'Keeps the label for assistive technology but hides it visually.',
  controlAttrs:
    "Attributes, listeners and a `ref` callback for the native control, for example Formisch's `field.props`.",
  size: 'Size. Where no default is listed, it falls back to the nearest `SoraProvider` `defaults`, then to `sora.config.ts`.',
  color:
    'Colour role. Where no default is listed, it falls back to the nearest `SoraProvider` `defaults`, then to `sora.config.ts`.',
  variant:
    'Visual variant. Where no default is listed, it falls back to the nearest `SoraProvider` `defaults`, then to `sora.config.ts`.',
  orientation: 'Layout direction.',
  placement: 'Preferred position relative to the trigger. It flips when there is no room.',
}
const SHARED_MODELS: Readonly<Record<string, string>> = {
  open: 'Whether it is open. Stays in sync with the native element, however it was opened or closed.',
}

/** The JSDoc text attached to a node (description only, tags dropped). */
function docOf(node: ts.Node): string {
  const blocks = ts.getJSDocCommentsAndTags(node).filter(ts.isJSDoc)
  return oneLine(blocks.map((block) => ts.getTextOfJSDocComment(block.comment) ?? '').join(' '))
}

/** A leading `/** ... *\/` comment in front of a statement that is not a declaration. */
function leadingDoc(node: ts.Node, source: ts.SourceFile): string {
  const ranges = ts.getLeadingCommentRanges(source.text, node.getFullStart()) ?? []
  const last = ranges.at(-1)
  if (!last) return ''
  const text = source.text.slice(last.pos, last.end)
  if (!text.startsWith('/**')) return ''
  return oneLine(
    text
      .replace(/^\/\*\*|\*\/$/g, '')
      .split('\n')
      .map((line) => line.replace(/^\s*\*\s?/, ''))
      .join(' '),
  )
}

const memberName = (name: ts.PropertyName): string =>
  ts.isStringLiteral(name) || ts.isNoSubstitutionTemplateLiteral(name) ? name.text : name.getText()

function membersOf(type: ts.TypeNode | undefined, source: ts.SourceFile): Member[] {
  const result: Member[] = []
  const visit = (node: ts.TypeNode | undefined): void => {
    if (!node) return
    if (ts.isIntersectionTypeNode(node)) {
      node.types.forEach(visit)
      return
    }
    if (ts.isParenthesizedTypeNode(node)) {
      visit(node.type)
      return
    }
    if (!ts.isTypeLiteralNode(node)) return
    for (const member of node.members) {
      if (ts.isPropertySignature(member) && member.type) {
        result.push({
          name: memberName(member.name),
          type: oneLine(member.type.getText(source)),
          optional: member.questionToken !== undefined,
          doc: docOf(member),
        })
      } else if (ts.isMethodSignature(member)) {
        const parameters = member.parameters.map((parameter) => oneLine(parameter.getText(source))).join(', ')
        result.push({
          name: memberName(member.name),
          type: parameters,
          optional: member.questionToken !== undefined,
          doc: docOf(member),
        })
      } else if (ts.isMappedTypeNode(member as unknown as ts.Node)) {
        // handled below
      }
    }
  }
  visit(type)
  return result
}

/** `defineX<T>(...)`: the call, wherever it sits in a statement. */
function findCalls(source: ts.SourceFile, name: string): ts.CallExpression[] {
  const calls: ts.CallExpression[] = []
  const visit = (node: ts.Node): void => {
    if (ts.isCallExpression(node) && ts.isIdentifier(node.expression) && node.expression.text === name) {
      calls.push(node)
    }
    ts.forEachChild(node, visit)
  }
  visit(source)
  return calls
}

function statementOf(node: ts.Node): ts.Node {
  let current = node
  while (current.parent && !ts.isSourceFile(current.parent)) current = current.parent
  return current
}

function readApi(file: string, code: string): Api {
  const { descriptor } = parse(code, { filename: file })
  const setup = descriptor.scriptSetup
  if (!setup) throw new Error(`${file}: no <script setup>`)
  const source = ts.createSourceFile(
    `${file}.ts`,
    setup.content,
    ts.ScriptTarget.ESNext,
    true,
    ts.ScriptKind.TS,
  )
  const api: Api = {
    generic: typeof setup.attrs['generic'] === 'string' ? setup.attrs['generic'] : '',
    props: [],
    models: [],
    events: [],
    slots: [],
    exposed: [],
  }

  // ---------------------------------------------------------------- props
  const propsCall = findCalls(source, 'defineProps')[0]
  const propsType = propsCall?.typeArguments?.[0]
  const propsName =
    propsType && ts.isTypeReferenceNode(propsType) ? propsType.typeName.getText(source) : undefined
  const defaults = new Map<string, string>()
  const declaration = propsCall?.parent
  if (declaration && ts.isVariableDeclaration(declaration) && ts.isObjectBindingPattern(declaration.name)) {
    for (const element of declaration.name.elements) {
      if (element.initializer && ts.isIdentifier(element.name)) {
        defaults.set(element.name.text, oneLine(element.initializer.getText(source)))
      }
    }
  }
  for (const statement of source.statements) {
    if (!ts.isInterfaceDeclaration(statement) || statement.name.text !== propsName) continue
    for (const member of statement.members) {
      if (!ts.isPropertySignature(member) || !member.type) continue
      const name = memberName(member.name)
      // `T | undefined` on an optional prop is how exactOptionalPropertyTypes is spelled; it is noise here.
      const type = oneLine(member.type.getText(source)).replace(/\s*\|\s*undefined$/, '')
      api.props.push({
        name,
        type,
        optional: member.questionToken !== undefined,
        doc: docOf(member) || (SHARED_PROPS[name] ?? ''),
        default: defaults.get(name) ?? '',
      })
    }
  }

  // --------------------------------------------------------------- models
  for (const call of findCalls(source, 'defineModel')) {
    const [first, second] = call.arguments
    const named = first && ts.isStringLiteral(first)
    const options = named ? second : first
    const detail: string[] = []
    if (options && ts.isObjectLiteralExpression(options)) {
      for (const property of options.properties) {
        if (!ts.isPropertyAssignment(property)) continue
        const key = property.name.getText(source)
        if (key === 'required' && property.initializer.kind === ts.SyntaxKind.TrueKeyword)
          detail.push('required')
        if (key === 'default') detail.push(`default \`${oneLine(property.initializer.getText(source))}\``)
      }
    }
    api.models.push({
      name: named ? first.text : 'modelValue',
      type: oneLine(call.typeArguments?.[0]?.getText(source) ?? 'unknown'),
      detail: detail.join(', '),
      doc: leadingDoc(statementOf(call), source) || (named ? (SHARED_MODELS[first.text] ?? '') : ''),
    })
  }
  // An explicit `modelValue` prop with an `update:modelValue` event is a v-model too.
  const modelValue = api.props.find((prop) => prop.name === 'modelValue')
  const emitsType = findCalls(source, 'defineEmits')[0]?.typeArguments?.[0]
  const emits = membersOf(emitsType, source)
  if (modelValue && emits.some((event) => event.name === 'update:modelValue')) {
    api.models.unshift({
      name: 'modelValue',
      type: modelValue.type,
      detail: modelValue.optional ? '' : 'required',
      doc: modelValue.doc,
    })
    api.props = api.props.filter((prop) => prop.name !== 'modelValue')
  }

  // ---------------------------------------------------------------- events
  api.events = emits.filter((event) => !event.name.startsWith('update:'))

  // ----------------------------------------------------------------- slots
  const slotsType = findCalls(source, 'defineSlots')[0]?.typeArguments?.[0]
  api.slots = membersOf(slotsType, source)
  // Template-literal slot families (`cell-${string}`) are declared with a mapped type.
  const mapped = slotsType ? /\[K in `([^`]+)`\]/.exec(slotsType.getText(source)) : null
  if (mapped?.[1]) {
    const generic = api.slots.find((slot) => slot.name === 'cell')
    api.slots.push({
      name: mapped[1].replace('${string}', '<key>'),
      type: generic?.type ?? '',
      optional: true,
      doc: 'One slot per key; takes precedence over the generic slot.',
    })
  }

  // --------------------------------------------------------------- exposed
  const exposeArgument = findCalls(source, 'defineExpose')[0]?.arguments[0]
  if (exposeArgument && ts.isObjectLiteralExpression(exposeArgument)) {
    for (const property of exposeArgument.properties) {
      if (!property.name) continue
      const name = property.name.getText(source)
      let type = ''
      if (ts.isGetAccessorDeclaration(property)) type = 'property'
      else if (ts.isMethodDeclaration(property)) type = 'method'
      else if (ts.isPropertyAssignment(property)) {
        type = ts.isArrowFunction(property.initializer) ? 'method' : 'property'
      } else if (ts.isShorthandPropertyAssignment(property)) type = 'method'
      api.exposed.push({ name, type, optional: false, doc: docOf(property) || leadingDoc(property, source) })
    }
  }

  return api
}

// ------------------------------------------------------------ gallery examples
/** `<DemoSection name="SoraX">…</DemoSection>` blocks of the gallery, by component name. */
async function readExamples(): Promise<Map<string, { file: string; code: string }>> {
  const examples = new Map<string, { file: string; code: string }>()
  for await (const file of glob('apps/gallery/src/demos/*.vue', { cwd: root })) {
    const { descriptor } = parse(await readFile(`${root}${file}`, 'utf8'), { filename: file })
    const template = descriptor.template?.content ?? ''
    for (const match of template.matchAll(/<DemoSection name="(\w+)">\n([\s\S]*?)\n {2}<\/DemoSection>/g)) {
      const [, name, body] = match
      if (!name || body === undefined) continue
      // Remove the indentation the block has inside the section.
      const lines = body.split('\n')
      const indent = Math.min(
        ...lines.filter((line) => line.trim() !== '').map((line) => /^ */.exec(line)?.[0].length ?? 0),
      )
      examples.set(name, { file, code: lines.map((line) => line.slice(indent)).join('\n') })
    }
  }
  return examples
}

// ------------------------------------------------------------------ markdown
const cell = (text: string): string => text.replace(/\|/g, '\\|').replace(/\n/g, ' ')
const code = (text: string): string => (text === '' ? '' : `\`${cell(text)}\``)

function table(headers: readonly string[], rows: readonly (readonly string[])[]): string {
  return [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map((row) => `| ${row.join(' | ')} |`),
  ].join('\n')
}

const list = (items: readonly string[]): string => items.map((item) => `- ${item}`).join('\n')

function render(
  entry: SoraComponentManifestEntry,
  api: Api,
  example: { file: string; code: string } | undefined,
): string {
  const importPath = entry.entry === 'forms' ? '@your-scope/ui/forms' : '@your-scope/ui'
  const parts: string[] = [
    BANNER,
    '',
    `# ${entry.name}`,
    '',
    entry.summary,
    '',
    table(
      ['', ''],
      [
        ['Category', entry.category],
        ['Import', code(`import { ${entry.name} } from '${importPath}'`)],
        ['Direct import', code(`import ${entry.name} from '@your-scope/ui/components/${entry.name}'`)],
        ['Source', `[\`packages/ui/src/${entry.source}\`](../../packages/ui/src/${entry.source})`],
        ...(api.generic ? [['Generic', code(api.generic)]] : []),
      ],
    ),
  ]

  if (api.props.length > 0) {
    parts.push(
      '',
      '## Props',
      '',
      table(
        ['Prop', 'Type', 'Default', 'Description'],
        api.props.map((prop) => [
          code(prop.name) + (prop.optional ? '' : ' **(required)**'),
          code(prop.type),
          code(prop.default),
          cell(prop.doc),
        ]),
      ),
    )
  }
  if (api.models.length > 0) {
    parts.push(
      '',
      '## Models',
      '',
      table(
        ['v-model', 'Type', '', 'Description'],
        api.models.map((model) => [
          code(model.name === 'modelValue' ? 'v-model' : `v-model:${model.name}`),
          code(model.type),
          cell(model.detail),
          cell(model.doc),
        ]),
      ),
    )
  }
  if (api.events.length > 0) {
    parts.push(
      '',
      '## Events',
      '',
      table(
        ['Event', 'Payload', 'Description'],
        api.events.map((event) => [code(event.name), code(event.type), cell(event.doc)]),
      ),
    )
  }
  if (api.slots.length > 0) {
    parts.push(
      '',
      '## Slots',
      '',
      table(
        ['Slot', 'Slot props', 'Description'],
        api.slots.map((slot) => [code(slot.name), code(slot.type), cell(slot.doc)]),
      ),
    )
  }
  if (api.exposed.length > 0) {
    parts.push(
      '',
      '## Exposed',
      '',
      'Available on a template ref of the component.',
      '',
      table(
        ['Member', 'Kind', 'Description'],
        api.exposed.map((member) => [code(member.name), member.type, cell(member.doc)]),
      ),
    )
  }

  parts.push('', '## Attributes', '', entry.attrs)
  if (entry.keyboard.length > 0) parts.push('', '## Keyboard', '', list(entry.keyboard))
  parts.push('', '## Accessibility', '', list(entry.a11y))
  parts.push('', '## Styling', '', list(entry.styling))
  if (example) {
    parts.push(
      '',
      '## Example',
      '',
      `From the gallery ([\`${example.file}\`](../../${example.file})), where it is type-checked and covered by the end-to-end tests. \`t()\` is the gallery's translation function; the state it binds is declared in that file.`,
      '',
      '```vue',
      example.code,
      '```',
    )
  }
  return `${parts.join('\n')}\n`
}

function renderIndex(): string {
  const parts = [
    BANNER,
    '',
    '# Components',
    '',
    `${componentManifest.length} components. Every page lists the props, models, events, slots and exposed members read from the source, plus attribute routing, keyboard interaction, accessibility notes, styling hooks and a live example.`,
  ]
  for (const category of componentCategories) {
    const entries = componentManifest.filter((entry) => entry.category === category)
    parts.push(
      '',
      `## ${category[0]?.toUpperCase()}${category.slice(1)}`,
      '',
      table(
        ['Component', 'Purpose'],
        entries.map((entry) => [`[${entry.name}](./${entry.name}.md)`, cell(entry.summary)]),
      ),
    )
  }
  return `${parts.join('\n')}\n`
}

// ---------------------------------------------------------------------- run
const examples = await readExamples()
const files = new Map<string, string>([['README.md', renderIndex()]])
const missingExamples: string[] = []
for (const entry of componentManifest) {
  const path = `${root}packages/ui/src/${entry.source}`
  const api = readApi(path, await readFile(path, 'utf8'))
  const example = examples.get(entry.name)
  if (!example) missingExamples.push(entry.name)
  files.set(`${entry.name}.md`, render(entry, api, example))
}
if (missingExamples.length > 0) {
  console.error(`docs: no gallery demo found for ${missingExamples.join(', ')}`)
  process.exit(1)
}

if (check) {
  const stale: string[] = []
  for (const [name, content] of files) {
    const path = `${outDir}/${name}`
    if (!existsSync(path) || (await readFile(path, 'utf8')) !== content) stale.push(name)
  }
  const extra = existsSync(outDir) ? (await readdir(outDir)).filter((name) => !files.has(name)) : []
  if (stale.length > 0 || extra.length > 0) {
    for (const name of stale) console.error(`docs: docs/components/${name} is out of date`)
    for (const name of extra) console.error(`docs: docs/components/${name} has no component`)
    console.error('Run `pnpm docs:components`.')
    process.exit(1)
  }
  console.log(`docs ok: ${files.size} files in docs/components are up to date`)
} else {
  await rm(outDir, { recursive: true, force: true })
  await mkdir(outDir, { recursive: true })
  for (const [name, content] of files) await writeFile(`${outDir}/${name}`, content)
  console.log(`docs: wrote ${files.size} files to docs/components`)
}
